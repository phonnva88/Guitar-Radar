CREATE TABLE IF NOT EXISTS radar_schema_version (
    version integer PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS app_state (
    id integer PRIMARY KEY CHECK (id = 1),
    paused_code text,
    worker_heartbeat_at timestamptz
);
INSERT INTO app_state (id) VALUES (1) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS monitored_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    url text NOT NULL UNIQUE,
    facebook_group_id text,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_success_at timestamptz,
    last_error_code text
);
CREATE TABLE IF NOT EXISTS collection_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL REFERENCES monitored_groups(id),
    status text NOT NULL CHECK (status IN ('queued','running','success','partial','failed','interrupted')),
    queued_at timestamptz NOT NULL DEFAULT now(),
    started_at timestamptz,
    finished_at timestamptz,
    error_code text,
    posts_count integer NOT NULL DEFAULT 0,
    window_complete boolean NOT NULL DEFAULT false,
    source text NOT NULL DEFAULT 'live'
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_run_per_group ON collection_runs (group_id)
    WHERE status IN ('queued','running');
CREATE TABLE IF NOT EXISTS listings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    confirmed_at timestamptz
);
CREATE TABLE IF NOT EXISTS posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES listings(id),
    platform text NOT NULL DEFAULT 'facebook',
    group_id bigint NOT NULL REFERENCES monitored_groups(id),
    post_id text NOT NULL,
    canonical_key text UNIQUE,
    url text,
    text text,
    author_id text,
    author_name text,
    posted_at timestamptz,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    text_fingerprint text,
    source text NOT NULL DEFAULT 'live',
    UNIQUE (platform, group_id, post_id)
);
CREATE TABLE IF NOT EXISTS media (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    url text NOT NULL,
    position integer NOT NULL,
    width integer,
    height integer,
    type_evidence text,
    UNIQUE(post_id, position)
);
CREATE INDEX IF NOT EXISTS posts_latest ON posts (posted_at DESC NULLS LAST, id DESC);
CREATE INDEX IF NOT EXISTS posts_group_latest ON posts (group_id, posted_at DESC NULLS LAST, id DESC);
CREATE INDEX IF NOT EXISTS posts_text_fingerprint ON posts (text_fingerprint) WHERE text_fingerprint IS NOT NULL;
INSERT INTO radar_schema_version(version) VALUES (1) ON CONFLICT DO NOTHING;
