-- Video is separate from the historical photo-only media table. Existing
-- image counts and has_images queries therefore retain their meaning.
CREATE TABLE IF NOT EXISTS videos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    position integer NOT NULL,
    video_id text,
    kind text NOT NULL CHECK (kind IN ('direct','reel','shared','live')),
    thumbnail_url text,
    duration_seconds double precision CHECK (duration_seconds >= 0 AND duration_seconds <= 100000000),
    width integer CHECK (width > 0),
    height integer CHECK (height > 0),
    playback_url text,
    playback_url_expires_at timestamptz,
    playback_url_ephemeral boolean NOT NULL DEFAULT false,
    UNIQUE(post_id, position)
);
